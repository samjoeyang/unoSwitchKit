import { invoke } from "@tauri-apps/api/core";
import type {
  AccountBalance,
  AppearanceMode,
  ShortcutReport,
  BtDevice,
  BundleUsage,
  CleanPreview,
  CleanResult,
  LargeFile,
  MemoryComparison,
  MemoryStat,
  PermissionState,
  Settings,
  SystemStats,
  SidecarStatus,
  ToggleStates,
  TrashItem,
  UpdateConfig,
} from "./types";

export const api = {
  getToggleStates: () => invoke<ToggleStates>("get_toggle_states"),
  getAppearanceMode: () => invoke<AppearanceMode>("get_appearance_mode"),
  setAppearanceMode: (mode: AppearanceMode) =>
    invoke<AppearanceMode>("set_appearance_mode", { mode }),
  cycleAppearanceMode: () => invoke<AppearanceMode>("cycle_appearance_mode"),
  openSystemScreenshot: () => invoke<void>("open_system_screenshot"),
  setShortcutBindings: (bindings: Record<string, string>) =>
    invoke<ShortcutReport[]>("set_shortcut_bindings", { bindings }),
  toggleDarkMode: () => invoke<boolean>("toggle_dark_mode"),
  toggleHideDesktop: () => invoke<boolean>("toggle_hide_desktop"),
  togglePreventSleep: () => invoke<boolean>("toggle_prevent_sleep"),
  emptyTrash: () => invoke<number>("empty_trash"),
  toggleHideDock: () => invoke<boolean>("toggle_hide_dock"),
  toggleShowHiddenFiles: () => invoke<boolean>("toggle_show_hidden_files"),
  toggleScreenClean: () => invoke<boolean>("toggle_screen_clean"),
  toggleStageManager: () => invoke<boolean>("toggle_stage_manager"),
  lockScreen: () => invoke<void>("lock_screen"),
  clearClipboard: () => invoke<void>("clear_clipboard"),
  startScreensaver: () => invoke<void>("start_screensaver"),
  closeAllApps: () => invoke<number>("close_all_apps"),
  releaseMemory: () => invoke<MemoryComparison>("release_memory"),
  flushDns: () => invoke<void>("flush_dns"),
  scanCleanup: () => invoke<CleanPreview>("scan_cleanup"),
  cleanSelected: (ids: string[]) =>
    invoke<CleanResult>("clean_selected", { ids }),
  bundleUsage: () => invoke<BundleUsage[]>("bundle_usage"),
  largeFiles: (thresholdMb: number) =>
    invoke<LargeFile[]>("large_files", { thresholdMb }),
  trashPath: (path: string) => invoke<string>("trash_path", { path }),
  listTrashItems: () => invoke<TrashItem[]>("list_trash_items"),
  restoreTrashItem: (trashedPath: string) =>
    invoke<void>("restore_trash_item", { trashed_path: trashedPath }),
  emptySwitchkitTrash: () => invoke<number>("empty_switchkit_trash"),
  getBalances: () => invoke<AccountBalance[]>("get_balances"),
  getMemoryStats: () => invoke<MemoryStat>("get_memory_stats"),
  getSystemStats: () => invoke<SystemStats>("get_system_stats"),
  getSettings: () => invoke<Settings>("get_settings"),
  saveSettings: (s: Settings) => invoke<void>("save_settings", { settings: s }),
  setLaunchAtLogin: (enabled: boolean) =>
    invoke<void>("set_launch_at_login", { enabled }),
  isLaunchAtLogin: () => invoke<boolean>("is_launch_at_login"),
  sidecarStatus: () => invoke<SidecarStatus>("sidecar_status"),
  btDevices: () => invoke<BtDevice[]>("bt_devices"),
  btConnect: (address: string) => invoke<boolean>("bt_connect", { address }),
  btDisconnect: (address: string) => invoke<boolean>("bt_disconnect", { address }),
  quitApp: () => invoke<void>("quit_app"),
  getUpdateConfig: () => invoke<UpdateConfig>("get_update_config"),
  getPermissionState: () => invoke<PermissionState>("get_permission_state"),
  refreshPermissions: () => invoke<PermissionState>("refresh_permissions"),
  acknowledgePermissionChange: () =>
    invoke<boolean>("acknowledge_permission_change"),
  copyResetCommand: () => invoke<void>("copy_reset_command"),
  openPrivacySettings: () => invoke<void>("open_privacy_settings"),
};
